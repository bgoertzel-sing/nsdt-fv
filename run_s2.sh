#!/usr/bin/env bash
# S2 from a clean checkout (plan 8.1): tests, then the DT arms on pinned core pairs, then reports/S2.md
# regenerated twice from the logs (must be byte-identical, R3).
#   pip install -r requirements.txt   # pyyaml, pytest, numpy, torch (CPU)
#   S1's base weights are needed (not committed): run ./run_s1.sh first, or copy runs/S1/base/base.pt and
#   runs/S1_seed1/base/base.pt to runs/S2/base/ and runs/S2_seed1/base/ (their hashes are checked).
#   ./run_s2.sh
set -euo pipefail
cd "$(dirname "$0")"
python3 -m pytest -q
run() { taskset -c "$1" python3 -m nsdt_fv.eval.s2 --config nsdt_fv/configs/S2.yaml --arm "$2" --seed "$3"; }
# each run uses 2 pinned cores; runs in one line execute in parallel on disjoint core pairs
run 0,1 D1 0 & run 2,3 D2 0 & run 4,5 D3 0 & run 6,7 D4 0 & wait
run 0,1 D1 1 & run 2,3 D2 1 & run 4,5 B2c 0 & wait
python3 -m nsdt_fv.eval.report_s2
cp nsdt_fv/reports/S2.md /tmp/S2.first.md
python3 -m nsdt_fv.eval.report_s2
cmp /tmp/S2.first.md nsdt_fv/reports/S2.md && echo "report regenerated byte-identically"
