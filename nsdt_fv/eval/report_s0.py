"""Generate reports/S0.md (format of plan A.6) from the raw logs of an S0 run. Tables are generated,
never typed (R3): every number below is computed here from runs/S0/*.jsonl and meta.json with the
counting helpers of eval/metrics.py.

    python -m nsdt_fv.eval.report_s0 [run_dir] [out.md]
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter

from .metrics import count, read_log, tally
from .s0 import t2_results
from . import t2_cases


def _t2_logs_from_file(path):
    lines = read_log(path)
    by = {}
    for ln in lines:
        by.setdefault(ln["run"], []).append(ln)
    _, ts_a = t2_cases.build_case_a()
    _, ts_b = t2_cases.build_case_b()
    _, ts_c = t2_cases.build_quarter_log("x", t2_cases.CASE_C["B2"])
    a_lines = by["T2/A"] + by.get("T2/other", [])
    return {"A": (a_lines, ts_a), "B": (by["T2/B"], ts_b), "C-B2": (by["T2/C-B2"], ts_c),
            "C-B6": (by["T2/C-B6"], ts_c)}


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def build(run_dir: str) -> str:
    meta = json.load(open(os.path.join(run_dir, "meta.json")))
    t1 = read_log(os.path.join(run_dir, "t1_checks.jsonl"))
    t3 = read_log(os.path.join(run_dir, "t3_guard.jsonl"))
    t2 = t2_results(_t2_logs_from_file(os.path.join(run_dir, "t2_synthetic.jsonl")))
    gt = [l for l in t1 if l["part"] == "gt"]
    mut = [l for l in t1 if l["part"] in ("proof_only", "proof_and_statement")]
    so = [l for l in t1 if l["part"] == "statement_only"]
    allm = mut + so
    n_gt, n_gt_ok = len(gt), count(gt, accepted=True)
    n_gt_true = count(gt, statement_true=True)
    n_mut, n_mut_ok = len(mut), count(mut, accepted=True)
    bugs = count(allm, soundness_bug=True)
    inst = sorted({l["instances"] for l in t1})
    t2_ok = all(abs(e - c) <= 1e-9 for _, _, e, c in t2)
    leaks = [l for l in t3 if l["part"] == "leak"]
    leak_ok = all(l["raised"] for l in leaks)
    controls = [l for l in t3 if l["part"] == "control"]
    ctrl_fp = count(controls, raised=True)
    t1_ok = n_gt_ok == n_gt and bugs == 0
    L = []
    L.append("# S0: ToyEq, checker, harness, metrics and hold-out guard")
    L.append("")
    L.append("Generated by nsdt_fv/eval/report_s0.py from the raw logs in nsdt_fv/runs/S0/ (rule R3). Do not edit by hand.")
    L.append("")
    L.append("## Identification")
    L.append("")
    L.append(_table(["item", "value"], [
        ["experiment", "S0 (plan 8.1, Stage S)"],
        ["arms", "none (harness experiment; no model is trained in S0)"],
        ["bases", "none (no pretrained weights)"],
        ["seeds", f"generator and mutation seed {meta['seed']}; instance seeds are sha256 of the statement or obligation id"],
        ["code commit", meta["code_commit"]],
        ["data version", meta["data_version"] + " (sha256 prefix over obligations.jsonl)"],
        ["environment", f"{meta['env']['cpu_count']} CPUs visible, {meta['env']['mem_gb']} GB RAM, nvidia-smi present: {meta['env']['nvidia_smi']}, Python {meta['env']['python']}, PyYAML {meta['env']['pyyaml']}"],
    ]))
    L.append("")
    L.append("Toy projects (C.3); window 1 = first half of the library, stream = six projects x two windows = 12 stages:")
    L.append("")
    L.append(_table(["project", "template", "functions (wrappers)", "lemmas", "window 1", "seed lemmas not proved", "candidates tried", "unproved by reference prover"],
                    [[p["name"], p["template"], f"{p['functions']} ({p['wrappers']})", p["lemmas"], p["window1"],
                      ", ".join(p["seed_failed"]) or "-", p["gen_stats"]["candidates"], p["gen_stats"]["unproved"]]
                     for p in meta["projects"]]))
    L.append("")
    L.append("The prelude (toy-prelude) is pretraining material for the base model and is not in the stream.")
    L.append("")
    L.append("## Results")
    L.append("")
    L.append("### T1: ToyEq checker")
    L.append("")
    L.append(_table(["quantity", "count"], [
        ["ground-truth proofs checked (stream + prelude)", n_gt],
        ["ground-truth proofs accepted", n_gt_ok],
        ["ground-truth statements true on all random ground instances", n_gt_true],
        ["random ground instances per statement", ", ".join(str(i) for i in inst)],
        ["mutated proofs (T1 proper)", n_mut],
        ["  of which against the original statement", count(mut, part="proof_only")],
        ["  of which against a mutated statement", count(mut, part="proof_and_statement")],
        ["mutated proofs accepted", n_mut_ok],
        ["  accepted, statement mutated (non-trivial soundness probes)", count(mut, accepted=True, statement_mutated=True)],
        ["mutated proofs whose statement is false on some instance", count(mut, statement_true=False)],
        ["supplementary: mutated statements with the ground-truth proof", len(so)],
        ["  accepted", count(so, accepted=True)],
        ["  false on some instance", count(so, statement_true=False)],
        ["**soundness bugs** (accepted and false on an instance), all mutants", bugs],
        ["canary: same mutants under a planted checker bug, accepted", count(allm, canary_accepted=True)],
        ["canary: soundness bugs flagged under the planted bug", count(allm, canary_flag=True)],
    ]))
    L.append("")
    L.append("Why mutants were rejected (first checker message, classified), T1 mutants:")
    L.append("")
    rc = Counter(l["reason"] for l in mut)
    L.append(_table(["reason", "mutants"], sorted(rc.items(), key=lambda x: -x[1])))
    L.append("")
    L.append("Acceptance by mutation operator (proof operators; statement operator where the statement was mutated):")
    L.append("")
    ops = sorted({l["proof_op"] for l in mut if l["proof_op"]})
    rows = []
    for op in ops:
        rows.append([op, count(mut, proof_op=op), count(mut, proof_op=op, accepted=True),
                     count(mut, proof_op=op, accepted=True, statement_mutated=True)])
    L.append(_table(["proof operator", "mutants", "accepted", "accepted with mutated statement"], rows))
    L.append("")
    sops = sorted({l["statement_op"] for l in allm if l.get("statement_op")})
    L.append(_table(["statement operator", "mutants", "statement false on an instance", "accepted", "accepted and false"],
                    [[op, count(allm, statement_op=op), count(allm, statement_op=op, statement_true=False),
                      count(allm, statement_op=op, accepted=True), count(allm, statement_op=op, soundness_bug=True)]
                     for op in sops]))
    L.append("")
    L.append("### T2: metrics on synthetic verdict logs with hand-computed answers")
    L.append("")
    L.append(_table(["case", "metric", "expected (hand-derived)", "computed by metrics.py", "abs. difference"],
                    [[c, m, repr(e), repr(v), f"{abs(e - v):.1e}"] for c, m, e, v in t2]))
    L.append("")
    L.append("Case A: T = 3, pass@1, |E_j| = 4, with ignored noise lines (other phase, other run, non-test target) in reverse order. "
             "Case B: T = 2, pass@2 from n = 4 samples (unbiased estimator). Case C: GC with case A as the arm. Derivations: nsdt_fv/eval/t2_cases.py.")
    L.append("")
    L.append("### T3: hold-out guard")
    L.append("")
    lt = sorted({l["leak"] for l in leaks})
    rows = []
    for x in lt:
        for var in ("stealth", "with_id"):
            sub = [l for l in leaks if l["leak"] == x and l["variant"] == var]
            rows.append([x, var, len(sub), count(sub, raised=True),
                         ", ".join(f"{k}: {v}" for k, v in sorted(tally(sub, "rule").items(), key=lambda kv: str(kv[0])))])
    L.append(_table(["injected leak", "variant", "injections", "raised", "rule that fired"], rows))
    L.append("")
    L.append("One injection per test obligation and leak type; 'stealth' carries no test identifier, so only the "
             "statement, proof-text and proof-state checks can catch it.")
    L.append("")
    dec = [l for l in t3 if l["part"] == "decoy"]
    ck = sorted({l["leak"] for l in controls})
    L.append(_table(["legitimate example (control)", "examples", "raised (false positives)"],
                    [[k, count(controls, leak=k), count(controls, leak=k, raised=True)] for k in ck]))
    L.append("")
    l2 = [l for l in t3 if l["part"] == "L2"][0]
    L.append(f"Limits: a distinctive test proof placed under an unrelated statement was caught in {count(dec, raised=True)} of {len(dec)} cases "
             f"(only distinctive proofs, at least 8 tokens and not the proof of any non-test lemma, are matched as free text). "
             f"L2: filter_edges removed {l2['edges_removed']} of {l2['edges_in']} store edges, all of them proof_uses edges of test statements: {l2['removed_all_test_proof_uses']}.")
    L.append("")
    L.append("## Gate evaluation")
    L.append("")
    L.append(_table(["condition (S0 part of gate G0)", "numbers", "met"], [
        ["T1: all ground-truth proofs accepted, no soundness bug among 1,000 mutants",
         f"{n_gt_ok}/{n_gt} accepted; {bugs} soundness bugs; {n_mut_ok} mutants accepted, {count(mut, accepted=True, statement_mutated=True)} of them with a mutated statement",
         "yes" if t1_ok else "NO"],
        ["T2: LA, FWD, ACC, F, BWT and GC reproduced to 1e-9", f"max abs. difference {max(abs(e - v) for _, _, e, v in t2):.1e} over {len(t2)} values", "yes" if t2_ok else "NO"],
        ["T3: guard raises on each of the five injected leaks", f"{count(leaks, raised=True)}/{len(leaks)} injections raised; {ctrl_fp} false positives on {len(controls)} legitimate examples",
         "yes" if leak_ok else "NO"],
        ["checker interface allows a Lean backend without changing trainer or evaluator",
         "runner and metrics import only backends/base.py; tests/test_G0_interface.py runs the same evaluation over ToyEqBackend and MockLeanBackend", "yes (S0 part; trainer exists from S1)"],
    ]))
    L.append("")
    L.append("G0 also needs the two toy phenomena (S1) and S2-S4; those are later experiments.")
    L.append("")
    L.append("## Anomalies and open issues")
    L.append("")
    L.append("See reports/ISSUES.md (interpretations of C.2, R4, R5 and section 5.3 that the plan leaves open; no protocol element was changed).")
    fails = [p for p in meta["projects"] if p["seed_failed"]]
    if fails:
        L.append("")
        L.append("Seed lemmas the reference prover could not prove within its limits (dropped from the library, as C.3 prescribes): " +
                 "; ".join(f"{p['name']}: {', '.join(p['seed_failed'])}" for p in fails) + ".")
    L.append("")
    L.append("## Cost")
    L.append("")
    tm = meta["timing"]
    L.append(_table(["item", "value"], [
        ["GPU-hours", "0"],
        ["wall time of this run (single process)", f"{tm['total_s']:.0f} s (stream {tm['build_stream_s']:.0f} s, T1 {tm['t1_s']:.0f} s, T2 {tm['t2_s']:.1f} s, T3 {tm['t3_s']:.0f} s)"],
        ["core-hours (one core busy)", f"{tm['total_s'] / 3600:.3f}"],
    ]))
    L.append("")
    L.append("## Recommended next step")
    L.append("")
    L.append("S1: train the toy baselines (B0, B2, B5-10, B6) on the twelve-stage stream and calibrate the toy until joint retraining beats the frozen base by 20 points and sequential fine-tuning forgets 10.")
    L.append("")
    return "\n".join(L)


def write_report(run_dir, out_path):
    text = build(run_dir)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(text)
    return out_path


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rd = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "runs", "S0")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "reports", "S0.md")
    print(write_report(rd, out))
