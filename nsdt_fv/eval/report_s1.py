"""Generate reports/S1.md from the raw S1 logs (rules R3 and R13, report format A.6).

    python -m nsdt_fv.eval.report_s1 [--run-dir nsdt_fv/runs/S1] [--out nsdt_fv/reports/S1.md]

Every number below is computed here from runs/S1/<arm>/verdicts.jsonl, runs/S1/test_sets.json,
runs/S1/test_obligations.jsonl and runs/S1/meta.json with eval/metrics.py (and eval/bootstrap.py
for intervals). Nothing is typed by hand.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
from collections import defaultdict

import numpy as np

from . import bootstrap as BS
from . import metrics as M

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARM_ORDER = ["B0", "B2", "B5-10", "B6"]
NAMES = {"B0": "frozen base, statement context", "B2": "sequential LoRA", "B5-10": "LoRA + replay of 10% of history",
         "B6": "joint retraining on all windows so far, LoRA"}


def pct(x):
    return f"{100 * x:.1f}"


def ci(lo_hi):
    return f"[{100 * lo_hi[0]:.1f}, {100 * lo_hi[1]:.1f}]"


def load(run_dir):
    meta = json.load(open(os.path.join(run_dir, "meta.json")))
    ts = json.load(open(os.path.join(run_dir, "test_sets.json")))
    test_sets = {int(j): ids for j, ids in ts["test_sets"].items()}
    obl = {}
    with open(os.path.join(run_dir, "test_obligations.jsonl")) as f:
        for line in f:
            o = json.loads(line)
            obl[o["id"]] = o
    arms = {}
    for arm in ARM_ORDER:
        p = os.path.join(run_dir, arm, "verdicts.jsonl.gz")
        if os.path.exists(p):
            with gzip.open(p, "rt") as f:
                vl = [json.loads(x) for x in f if x.strip()]
            arms[arm] = {"lines": vl,
                         "train": M.read_log(os.path.join(run_dir, arm, "train.jsonl")),
                         "evalsets": json.load(open(os.path.join(run_dir, arm, "evalsets.json")))}
    return meta, ts["stages"], test_sets, obl, arms


def t4(arms, test_sets):
    """T4: evaluation sets identical across arms, by hash: (a) the eval-set hashes each arm recorded
    for every cell, (b) the set of target ids per cell read back from each arm's verdict log."""
    rec = {a: d["evalsets"] for a, d in arms.items()}
    first = rec[next(iter(rec))]
    cells = sorted(set().union(*[set(r) for r in rec.values()]), key=lambda c: tuple(map(int, c.split(","))))
    rec_ok = all(r.get(c) == first.get(c) for r in rec.values() for c in cells)
    logged = {}
    sets_ok = True
    for a, d in arms.items():
        per = defaultdict(set)
        for ln in d["lines"]:
            per[(ln["stage"], ln["eval_set"])].add(ln["target_id"])
            if ln["target_id"] not in test_sets[ln["eval_set"]]:
                sets_ok = False
        h = hashlib.sha256()
        for key in sorted(per):
            h.update(json.dumps([list(key), sorted(per[key])]).encode())
        logged[a] = h.hexdigest()
    ids_ok = len(set(logged.values())) == 1
    return {"cells": len(cells), "recorded_hashes_equal": rec_ok, "logged_id_sets_equal": ids_ok,
            "lines_in_declared_sets": sets_ok, "passed": rec_ok and ids_ok and sets_ok,
            "logged_digest": {a: h[:16] for a, h in logged.items()}}


def build(run_dir, out_path):
    meta, stages, test_sets, obl, arms = load(run_dir)
    cfg = meta["config"]
    k = cfg["eval"]["k"]
    T = len(test_sets)
    res, A, P = {}, {}, {}
    for arm, d in arms.items():
        run = meta["arms"][arm]["run"]
        res[arm], A[arm] = M.metrics_from_log(d["lines"], test_sets, k, run=run)
        P[arm] = BS.per_obligation(d["lines"], test_sets, k, run=run)
    if "B6" in res and "B2" in res:
        for arm in res:
            res[arm]["GC"] = M.gap_closed(res[arm]["ACC"], res["B2"]["ACC"], res["B6"]["ACC"])
    B = cfg["bootstrap"]["resamples"]
    R = BS.draws(test_sets, B, cfg["bootstrap"]["seed"])
    boot = {arm: BS.resampled_metrics(P[arm], T, R) for arm in P}
    ident = {j: np.arange(len(ids))[None, :] for j, ids in test_sets.items()}
    for arm in P:                         # bootstrap code on the identity resample must equal metrics.py
        chk = BS.resampled_metrics(P[arm], T, ident)
        for key in ("LA", "FWD", "ACC", "F", "BWT"):
            if abs(float(chk[key][0]) - res[arm][key]) > 1e-9:
                raise RuntimeError(f"bootstrap/metrics disagree on {arm} {key}")
    lines = []
    w = lines.append
    w("# S1: baselines on the toy stream (B0, B2, B5-10, B6)")
    w("")
    w("Generated by `python -m nsdt_fv.eval.report_s1` from `nsdt_fv/runs/S1/` (rule R3); do not edit by hand.")
    w("")
    w("## Identification")
    w("")
    w(f"- Experiment: S1 (plan 8.1). Arms: {', '.join(f'{a} ({NAMES[a]})' for a in arms)}.")
    b = meta["base"]
    w(f"- Base: tiny decoder-only transformer trained from scratch on the toy-prelude project only "
      f"({b['params']:,} parameters; d={cfg['model']['d']}, {cfg['model']['layers']} layers, "
      f"{cfg['model']['heads']} heads, ff={cfg['model']['ff']}; base hash `{b['hash']}`; "
      f"{b['stats']['n_examples']} prelude examples, {b['stats']['steps']} steps, final loss {b['stats']['last_loss']:.3f}).")
    ad = cfg["adapt"]
    w(f"- Adapters (B2, B5-10, B6): LoRA r={ad['lora_r']}, alpha={ad['lora_alpha']} on every linear "
      f"layer, base frozen; {ad['epochs']} epochs per stage (B6: {ad.get('joint_epochs', ad['epochs'])} "
      f"epochs over the union, adapters re-initialised each stage); batch {ad['batch']}, lr {ad['lr']}.")
    w(f"- Seeds: run seed {meta['seed']}, stream seed {cfg['stream']['seed']}; sampling seeds = sha256(run|stage|obligation|sample) (R6). "
      f"Bootstrap: {B} resamples, seed {cfg['bootstrap']['seed']}.")
    w(f"- Code commit: `{meta['code_commit']}`. Data version: `{meta['data_version']}` "
      f"({meta['stream']['obligations']} obligations; ToyEq checker sha `{meta['toolchain']['toyeq_checker_sha']}`).")
    v = meta["versions"]
    w(f"- Versions: Python {v['python']}, torch {v['torch']}, numpy {v['numpy']}, PyYAML {v['pyyaml']}; {v['platform']}; "
      f"{meta['threads']} torch threads, CPU affinity {meta['cpu_affinity']}.")
    w(f"- Stream: {T} stages ({', '.join(stages)}); |E_j| = {', '.join(str(len(test_sets[j])) for j in range(1, T + 1))} "
      f"(total {sum(len(x) for x in test_sets.values())}). Sampling: pass@{k}, temperature {cfg['eval']['temperature']}, no repair.")
    w("")
    w("## Metric tables")
    w("")
    w(f"Points (percent). Intervals: 95% bootstrap over obligations, resampled within each E_j ({B} resamples).")
    w("")
    w("| Arm | LA | FWD | ACC | F | BWT | GC |")
    w("|---|---|---|---|---|---|---|")
    for arm in arms:
        r, bt = res[arm], boot[arm]
        gc = f"{res[arm]['GC']:.3f}" if "GC" in res[arm] else "n/a"
        w(f"| {arm} | " + " | ".join(f"{pct(r[m])} {ci(BS.interval(bt[m]))}" for m in ("LA", "FWD", "ACC", "F", "BWT"))
          + f" | {gc} |")
    w("")
    w("GC = (ACC_arm - ACC_B2) / (ACC_B6 - ACC_B2); it is 0 for B2 and 1 for B6 by definition.")
    w("")
    triv = {j: np.array([obl[i]["closed_by_baseline_tactics"] for i in test_sets[j]]) for j in test_sets}
    n_triv = int(sum(t.sum() for t in triv.values()))
    n_all = sum(len(x) for x in test_sets.values())
    w(f"Stratum by the baseline closing tactics (section 7; toy list `refl`, `simp refl`): pass@{k} after the last stage, "
      f"pooled over the obligations of all E_j ({n_triv} trivial, {n_all - n_triv} non-trivial obligations).")
    w("")
    w("| Arm | trivial | non-trivial | all |")
    w("|---|---|---|---|")
    for arm in arms:
        vals = np.concatenate([P[arm][(T, j)] for j in range(1, T + 1)])
        tv = np.concatenate([triv[j] for j in range(1, T + 1)])
        w(f"| {arm} | {pct(vals[tv].mean())} | {pct(vals[~tv].mean())} | {pct(vals.mean())} |")
    w("")
    gc_ = cfg["gate"]
    w("## Gate evaluation (plan 8.1, S1 calibration targets)")
    w("")
    gate = {}
    if "B6" in res and "B0" in res:
        for key in ("ACC", "LA"):
            diff = boot["B6"][key] - boot["B0"][key]
            d0 = res["B6"][key] - res["B0"][key]
            ok = 100 * d0 >= gc_["gap_points"]
            if key == "ACC":
                gate["gap"] = ok
            w(f"- Gap on {key}: {key}(B6) - max({key}(B0), {key}(B1)) = {pct(res['B6'][key])} - {pct(res['B0'][key])} = "
              f"**{100 * d0:.1f} points** (paired 95% interval {ci(BS.interval(diff))}); target >= {gc_['gap_points']}: "
              f"**{'met' if ok else 'not met'}**{' (gate metric)' if key == 'ACC' else ' (for reference)'}.")
        w("  B1 is not an S1 arm (plan 8.1 lists B0, B2, B5-10, B6), so the maximum is over B0 alone.")
    if "B2" in res:
        f0 = res["B2"]["F"]
        ok = 100 * f0 >= gc_["forgetting_points"]
        gate["forgetting"] = ok
        w(f"- Forgetting of B2: F = **{100 * f0:.1f} points** (95% interval {ci(BS.interval(boot['B2']['F']))}); "
          f"target >= {gc_['forgetting_points']}: **{'met' if ok else 'not met'}**.")
    t4r = t4(arms, test_sets)
    gate["T4"] = t4r["passed"]
    w(f"- T4 (evaluation sets identical across arms, by hash): **{'passed' if t4r['passed'] else 'FAILED'}**. "
      f"{t4r['cells']} cells (t, j); recorded eval-set hashes equal across arms: {t4r['recorded_hashes_equal']}; "
      f"target-id sets per cell read back from the verdict logs equal: {t4r['logged_id_sets_equal']} "
      f"(digests {', '.join(f'{a} `{h}`' for a, h in t4r['logged_digest'].items())}); every line in its declared E_j: "
      f"{t4r['lines_in_declared_sets']}.")
    g = meta["guard"]
    excl = g.get("base_examples_excluded", [])
    w(f"- Hold-out guard (R4, L1-L4): {g['checked']} training examples passed `HoldoutGuard.check` in the final run "
      f"(base and all arms; a raise aborts the run; raises during training: {g['raised'] - len(excl)}). "
      f"Wake/test identifier overlap: {g['train_eval_id_overlap']}. Training examples whose statement is a test statement: "
      f"{g['train_examples_with_test_statement']}. Leak canaries (a test obligation injected as a wake example) raised: "
      f"{sum(c['raised'] for c in g['leak_canaries'])}/{len(g['leak_canaries'])} "
      f"({'; '.join(c.get('rule', '') + ' ' + c.get('detail', '') for c in g['leak_canaries'])}). "
      f"Prelude (base) examples excluded by the guard: {len(excl)}"
      + (f" ({'; '.join(e['source_ids'][0] + ': ' + e['detail'] for e in excl)})" if excl else "")
      + ". L4 event order checked after every evaluation.")
    canary = meta["canary"]
    gate["canary"] = canary["passed"]
    w(f"- Known-answer canary: ground-truth proofs through the same `evaluate()` and metrics path give "
      f"LA={canary['metrics']['LA']:.3f}, ACC={canary['metrics']['ACC']:.3f}, F={canary['metrics']['F']:.3f} over "
      f"{canary['cells']} cells: **{'passed' if canary['passed'] else 'FAILED'}**.")
    allok = all(gate.values()) and len(gate) == 5
    w("")
    w(f"**S1 condition {'met' if allok else 'not met'}** (gap: {gate.get('gap')}, forgetting: {gate.get('forgetting')}, "
      f"T4: {gate.get('T4')}, canary: {gate.get('canary')}).")
    w("")
    rep_dir = os.path.join(os.path.dirname(run_dir), "S1_seed1")
    if os.path.exists(os.path.join(rep_dir, "meta.json")):
        rmeta, _, rts, _, rarms = load(rep_dir)
        w("## Replicate with another training seed (supplementary)")
        w("")
        w(f"Same stream and evaluation sets, run seed {rmeta['seed']} (new base and arm initialisation), arms "
          f"{', '.join(rarms)}; logs in `nsdt_fv/runs/S1_seed1/`, code `{rmeta['code_commit']}`. Not used for the gate.")
        w("")
        w("| Arm | LA | FWD | ACC | F | BWT |")
        w("|---|---|---|---|---|---|")
        for arm, d in rarms.items():
            mm, _ = M.metrics_from_log(d["lines"], rts, k, run=rmeta["arms"][arm]["run"])
            w(f"| {arm} | " + " | ".join(pct(mm[x]) for x in ("LA", "FWD", "ACC", "F", "BWT")) + " |")
        w("")
    w("## Accuracy matrices a[t, j] (points)")
    w("")
    w("Rows: model after stage t (0 = base). Columns: E_j. Only the cells the metrics use are evaluated (j <= t + 1).")
    for arm in arms:
        w("")
        w(f"**{arm}**")
        w("")
        w("| t \\ j | " + " | ".join(str(j) for j in range(1, T + 1)) + " |")
        w("|---" * (T + 1) + "|")
        for t in range(0, T + 1):
            w(f"| {t} | " + " | ".join(pct(A[arm][(t, j)]) if (t, j) in A[arm] else "" for j in range(1, T + 1)) + " |")
    w("")
    w("## Training per stage")
    w("")
    w("| Arm | examples per stage (window+replayed) | optimizer steps | training tokens | "
      "earlier-window proof bytes read | guard checks |")
    w("|---|---|---|---|---|---|")
    for arm, d in arms.items():
        tr = d["train"]
        ex = ", ".join(f"{s['n_window']}+{s.get('n_replay', 0)}" for s in tr)
        w(f"| {arm} | {ex} | {sum(s.get('steps', 0) for s in tr)} | {sum(s.get('train_tokens', 0) for s in tr):,} | "
          f"{tr[-1].get('history_bytes_cum', 0):,} | {sum(s.get('guard_checked', 0) for s in tr)} |")
    w("")
    w("## Cost")
    w("")
    tot = 0.0
    w("| Arm | wall (s) | training (s) | sampling (s) | core-hours (2 cores) |")
    w("|---|---|---|---|---|")
    for arm in arms:
        a = meta["arms"][arm]
        tot += a["wall_s"]
        w(f"| {arm} | {a['wall_s']:.0f} | {a['train_s']:.0f} | {a['generate_s']:.0f} | {2 * a['wall_s'] / 3600:.3f} |")
    bw = meta["base"]["stats"].get("wall_s", 0.0)
    w("")
    w(f"Base pretraining {bw:.0f} s; stream build {meta['stream_build_s']:.0f} s. Total over base and arms "
      f"{(tot + bw) / 60:.1f} minutes, {2 * (tot + bw) / 3600:.2f} core-hours. GPU-hours: 0 (CPU only).")
    w("")
    notes = os.path.join(os.path.dirname(out_path), "S1_notes.md")
    if os.path.exists(notes):
        w(open(notes).read().strip())
        w("")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    summary = {"metrics": res, "t4": t4r, "gate": gate, "condition_met": allok}
    with open(os.path.join(run_dir, "report_summary.json"), "w") as f:
        json.dump(summary, f, indent=1, sort_keys=True, default=float)
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", default=os.path.join(HERE, "runs", "S1"))
    ap.add_argument("--out", default=os.path.join(HERE, "reports", "S1.md"))
    a = ap.parse_args(argv)
    s = build(a.run_dir, a.out)
    print(json.dumps({"gate": s["gate"], "condition_met": s["condition_met"]}))
    print(json.dumps(s["metrics"], default=float))


if __name__ == "__main__":
    main()
