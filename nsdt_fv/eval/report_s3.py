"""Generate reports/S3.md from the raw S3 logs and the S1/S2 reference logs (rules R3 and R13, format A.6).

    python -m nsdt_fv.eval.report_s3 [--out nsdt_fv/reports/S3.md]

Reads runs/S3/<arm>/ (D1 re-run, N-A .. N-E), runs/S2/D1/ and runs/S1/{B0,B2}/. Every number is
computed here from verdict logs, dream and conjecture logs, channel item logs, training-example logs
and train.jsonl. The stream is rebuilt deterministically (data version checked) to re-check channel B's
logged machine proofs with the checker (T10) and to map source ids to windows (T9).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from collections import defaultdict

import numpy as np

from . import bootstrap as BS
from . import metrics as M
from .report_s1 import t4 as t4_check
from .report_s2 import ci, gz, load_run, pct

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N_ARMS = ["N-A", "N-B", "N-C", "N-D", "N-E"]
CH_NAME = {"A": "artifact mining", "B": "dependency composition", "C": "exploration by execution",
           "D": "perturb and repair", "E": "proof-plan induction"}
KEYS = ("LA", "FWD", "ACC", "F", "BWT")
KINDS = {"A": ["nextstate", "premise", "unfold", "statement"], "B": ["statement"], "C": ["statement"],
         "D": ["repair", "priority"], "E": ["plan", "priority"]}
STMT = {"statement", "priority"}
BT = "\u0060"


def build(out_path):
    ts = json.load(open(os.path.join(HERE, "runs/S1/test_sets.json")))
    test_sets = {int(j): ids for j, ids in ts["test_sets"].items()}
    stages = ts["stages"]
    T = len(test_sets)
    obl = {}
    for line in open(os.path.join(HERE, "runs/S1/test_obligations.jsonl")):
        o = json.loads(line)
        obl[o["id"]] = o
    runs = {}
    m1 = json.load(open(os.path.join(HERE, "runs/S1/meta.json")))
    for a in ("B0", "B2"):
        r = load_run(os.path.join(HERE, "runs/S1"), a, s1=True)
        r["run"] = m1["arms"][a]["run"]
        runs[a] = r
    runs["D1 (S2)"] = load_run(os.path.join(HERE, "runs/S2"), "D1")
    for a in ["D1"] + N_ARMS:
        r = load_run(os.path.join(HERE, "runs/S3"), a)
        if r is None:
            raise RuntimeError(f"missing run runs/S3/{a}")
        p = os.path.join(HERE, "runs/S3", a, "channels.jsonl.gz")
        r["channels"] = gz(p) if os.path.exists(p) else []
        runs["D1 (S3)" if a == "D1" else a] = r
    s3 = ["D1 (S3)"] + N_ARMS
    cfg = runs["N-A"]["meta"]["config"]
    k = cfg["eval"]["k"]
    res, P = {}, {}
    for key, r in runs.items():
        res[key], _ = M.metrics_from_log(r["lines"], test_sets, k, run=r["run"])
        P[key] = BS.per_obligation(r["lines"], test_sets, k, run=r["run"])
    R = BS.draws(test_sets, cfg["bootstrap"]["resamples"], cfg["bootstrap"]["seed"])
    boot = {key: BS.resampled_metrics(P[key], T, R) for key in P}
    ident = {j: np.arange(len(ids))[None, :] for j, ids in test_sets.items()}
    for key in P:
        chk = BS.resampled_metrics(P[key], T, ident)
        for m in KEYS:
            if abs(float(chk[m][0]) - res[key][m]) > 1e-9:
                raise RuntimeError(f"bootstrap/metrics disagree on {key} {m}")

    def diff(a, b, m):
        return res[a][m] - res[b][m], BS.interval(boot[a][m] - boot[b][m])

    def nt_vec(key):
        return np.array([P[key][(T, j)][n] > 0 for j, ids in test_sets.items() for n, i in enumerate(ids)
                         if not obl[i]["closed_by_baseline_tactics"]], dtype=float)

    def nt_solved(key):
        return int(nt_vec(key).sum())

    def sgn(lh):
        return "excludes 0" if lh[0] > 0 or lh[1] < 0 else "includes 0"

    L = []
    w = L.append
    w("# S3: symbolic channels A-E on the toy (N-A to N-E)")
    w("")
    w(f"Generated by {BT}python -m nsdt_fv.eval.report_s3{BT} from {BT}nsdt_fv/runs/S3/{BT}, {BT}nsdt_fv/runs/S2/D1/{BT} and "
      f"{BT}nsdt_fv/runs/S1/{BT} (rule R3); do not edit by hand.")
    w("")
    w("## Identification")
    w("")
    m0 = runs["N-A"]["meta"]
    w("- Experiment: S3 (plan 8.1, A.7): channels A-E (section 4, C.5) behind the A.3 Channel interface, each run on top "
      "of D1 (DT-ref, A.4; not the DT core). Arms: " + "; ".join(f"{a}: D1 + channel {a[-1]} ({CH_NAME[a[-1]]})" for a in N_ARMS) +
      "; D1 (S3): S2's D1 re-run through the S3 driver with no channel (equivalence check). Reference arms recomputed "
      "from their logs: D1 (S2), B0 and B2 (S1).")
    w(f"- Base: S1's seed-0 tiny transformer, frozen ({m0['base']['params']:,} parameters), hash {BT}{m0['base']['hash']}{BT}; "
      f"cap as S2 ({m0['cap']['trainable_params']:,} trainable parameters).")
    dc = cfg["dream"]
    w(f"- Budget per stage (= D1; plan C5 'each at the dream budget of D1'): re-derivation {dc['nrem_statements']} statements x "
      f"{dc['candidates']} candidates; conjecture sleep at most {dc['rem_conjectures']} statements x {dc['candidates']} candidates, "
      f"the model's own conjectures first, then the channel's statements in its ranking; channel priorities (D, E) add "
      f"{cfg['prio_weight']} to the A.4 weight; channel wake examples join the window's wake epoch. Channel caps and limits per stage: " +
      "; ".join(f"{c}: " + ", ".join(f"{kk} {v}" for kk, v in sorted(cfg['channels'][c].items())) for c in "ABCDE") + ".")
    w(f"- Seeds: run seed 0 for every arm; sampling seeds of every S3 arm = those of S2's D1 ({BT}{m0['seed_run']}{BT}), so arms "
      f"differ only through training (common random numbers). Bootstrap {cfg['bootstrap']['resamples']} resamples, seed "
      f"{cfg['bootstrap']['seed']}.")
    commits = sorted({runs[x]["meta"]["code_commit"] for x in s3})
    w(f"- Code commit at run start: {', '.join(BT + c + BT for c in commits)}. Data version {BT}{m0['data_version']}{BT} "
      f"(S2 D1: {BT}{runs['D1 (S2)']['meta']['data_version']}{BT}). ToyEq checker sha {BT}{m0['toolchain']['toyeq_checker_sha']}{BT}.")
    v = m0["versions"]
    w(f"- Versions: Python {v['python']}, torch {v['torch']}, numpy {v['numpy']}, PyYAML {v['pyyaml']}; {v['platform']}; "
      f"{m0['threads']} torch threads; CPU affinity: " + ", ".join(f"{a} {runs[a]['meta']['cpu_affinity']}" for a in s3) + ".")
    w(f"- Stream and evaluation: as S1/S2 ({T} stages, |E| = {sum(len(x) for x in test_sets.values())}, pass@{k}, "
      f"temperature {cfg['eval']['temperature']}, no repair).")
    w("")
    w("## Channel yield per stage")
    w("")
    w(f"Per channel and item kind. 'cand' = items the channel produced and offered to the guard; 'refused' = refused by "
      f"HoldoutGuard.check; 'emitted' = passed the guard, eligible (statements: not a store duplicate and not emitted before by "
      f"the channel; auxiliary examples: confirmed by the checker and within max_len) and within the per-stage cap; "
      f"'acc' = emitted items the checker accepted (the check per kind is in each channel's docstring); 'nt' = emitted, accepted "
      f"statements the baseline tactics ({BT}refl{BT}, {BT}simp refl{BT}) do not close; 'dup' = candidates whose statement is a store "
      f"statement (repository statement of a seen snapshot or dream-library entry). Counts are read from each N arm's channels.jsonl.gz.")
    w("")
    ysum = {}
    for a in N_ARMS:
        cid = a[-1]
        recs = runs[a]["channels"]
        w(f"**Channel {cid} ({CH_NAME[cid]}), arm {a}**")
        w("")
        hdr = ["stage"]
        for kd in KINDS[cid]:
            hdr += [f"{kd} cand", "refused", "emitted", "acc"] + (["nt", "dup"] if kd in STMT else [])
        w("| " + " | ".join(hdr) + " |")
        w("|" + "---|" * len(hdr))
        tot = defaultdict(int)
        rules = defaultdict(int)
        for t in range(1, T + 1):
            row = [str(t)]
            for kd in KINDS[cid]:
                rs = [r for r in recs if r["stage"] == t and r["what"] == kd]
                ref = [r for r in rs if r["guard"] != "pass"]
                for r in ref:
                    rules[f"{kd} {r['guard']}"] += 1
                em = [r for r in rs if r["emitted"]]
                acc = [r for r in em if r["accepted"]]
                vals = [len(rs), len(ref), len(em), len(acc)]
                if kd in STMT:
                    vals += [sum(1 for r in acc if r.get("trivial") is False), sum(1 for r in rs if r.get("dup_store"))]
                for name, x in zip(["cand", "refused", "emitted", "acc", "nt", "dup"], vals):
                    tot[(kd, name)] += x
                claim = any(r["accepted"] is not None for r in rs)
                if not claim:                      # D's priorities point at store statements; they assert nothing
                    vals[3] = "-"
                    if kd in STMT:
                        vals[4] = "-"
                row += [str(x) for x in vals]
            w("| " + " | ".join(row) + " |")
        row = ["all"]
        for kd in KINDS[cid]:
            claim = any(r["accepted"] is not None for r in recs if r["what"] == kd)
            for name in ["cand", "refused", "emitted", "acc"] + (["nt", "dup"] if kd in STMT else []):
                row.append(str(tot[(kd, name)]) if claim or name not in ("acc", "nt") else "-")
        w("| " + " | ".join(row) + " |")
        w("")
        ysum[cid] = {"tot": dict(tot), "rules": dict(rules)}
        extra = (" Guard refusals by kind and rule: " + ", ".join(f"{r_} {n}" for r_, n in sorted(rules.items())) + ".") if rules else ""
        noclaim = [kd for kd in KINDS[cid] if not any(r["accepted"] is not None for r in recs if r["what"] == kd)]
        w(f"Emitted {sum(tot[(kd, 'emitted')] for kd in KINDS[cid])} items, of which checker-accepted "
          f"{sum(tot[(kd, 'acc')] for kd in KINDS[cid])}" +
          (f" ({', '.join(noclaim)}: pointers to store statements, no claim to check)" if noclaim else "") + f".{extra}")
        w("")
    w("**Channel B** candidates without a checker-accepted machine proof (never emitted), per stage: " +
      ", ".join(str(sum(1 for r in runs["N-B"]["channels"] if r["stage"] == t and r["what"] == "unproved")) for t in range(1, T + 1)) + ".")
    w("")
    w("**Channel C counterexample statistics** per stage: terms evaluated, largest term size reached, value classes, candidate "
      "equations (term agrees with a class representative on all 200 inputs), classes that agreed with an earlier class on the "
      "first 5 (20) inputs and were separated by a counterexample within the 200, candidates refuted on 200 fresh inputs, "
      "evaluations stopped by the budget, duplicate or unparsable candidates, survivors offered to the guard.")
    w("")
    w("| stage | terms | max size | classes | candidates | sep. after 5 | sep. after 20 | fresh cex | eval limit | dup/unparsed | survivors |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    ctot = defaultdict(int)
    for t in range(1, T + 1):
        st = next(r["stats"] for r in runs["N-C"]["channels"] if r["stage"] == t and r["what"] == "stats")
        vals = [st["terms"], st["max_size_reached"], st["classes"], st["candidates"], st["sep_after_5"], st["sep_within_200"],
                st["fresh_counterexample"], st["eval_limit"] + st["fresh_limit"], st["dup_or_unparsed"], st["survivors"]]
        for i, x in enumerate(vals):
            ctot[i] += x
        w(f"| {t} | " + " | ".join(str(x) for x in vals) + " |")
    w("| all | " + " | ".join(str(ctot[i]) if i != 1 else "-" for i in range(10)) + " |")
    w("")
    meth = [r for r in runs["N-E"]["channels"] if r["what"] == "methods"]
    w("**Channel E methods** (anti-unified skeletons with support >= 5) per stage: " + "; ".join(
        f"{r['stage']}: " + ", ".join(f"{BT}{m['text']}{BT} ({m['support']})" for m in r["methods"]) for r in meth) + ".")
    w("")
    w("## What the learner did with the channel material")
    w("")
    w("Conjecture sleep: channel statements offered (after the model's conjectures) and their status ('too long': the prompt "
      "would leave less than conj_max_new tokens of the context, the rule D1 applies to its own conjecture prompts); the model's proof attempts "
      "on the attempted ones; accepted candidates; accepted candidates for statements the baseline tactics do not close; "
      "statements added to the dream library (all sources). Wake: channel examples trained. Re-derivation: priority statements "
      "drawn / priority statements in the pool, summed over stages.")
    w("")
    w("| Arm | offered | parse err | too long | in repo | dup | L3 | over budget | attempted | attempts | acc | nt acc | library added | wake examples | prio drawn/pool |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    use = {}
    for a in s3:
        r = runs[a]
        cj = [c for c in r["conjectures"] if c.get("origin") == "channel"]
        stt = defaultdict(int)
        for c in cj:
            stt[c["status"]] += 1
        att = {(c["stage"], c["statement"]) for c in cj if c["status"] == "attempted"}
        dl = [ln for ln in r["dreams"] if ln["phase"] == "rem" and (ln["stage"], ln["statement"]) in att]
        acc = [ln for ln in dl if ln["accepted"]]
        nta = [ln for ln in acc if not ln.get("trivial")]
        lib = sum(tr["rem"]["library_added"] for tr in r["train"])
        wk = sum(1 for x in r["train_examples"] if x["phase"] == "wake_channel")
        pp = sum(tr["nrem"].get("prio_picked", 0) for tr in r["train"])
        ppool = sum(tr["nrem"].get("prio_pool", 0) for tr in r["train"])
        use[a] = {"offered": len(cj), "attempted": stt["attempted"], "attempts": len(dl), "acc": len(acc), "nt": len(nta),
                  "lib": lib, "wake": wk, "prio_picked": pp}
        w(f"| {a} | {len(cj)} | {stt['parse_error']} | {stt['too_long']} | {stt['in_repository']} | {stt['duplicate']} | {stt['test_statement']} | "
          f"{stt['over_budget']} | {stt['attempted']} | {len(dl)} | {len(acc)} | {len(nta)} | {lib} | {wk} | {pp}/{ppool} |")
    w("")
    w("## Metric tables")
    w("")
    w("Points (percent). Intervals: 95% bootstrap over obligations, resampled within each E_j, paired across arms.")
    w("")
    w("| Arm | LA | FWD | ACC | F | BWT | non-trivial solved |")
    w("|---|---|---|---|---|---|---|")
    order = ["B0", "B2", "D1 (S2)", "D1 (S3)"] + N_ARMS
    n_nt = sum(1 for i in obl if not obl[i]["closed_by_baseline_tactics"])
    for key in order:
        cells = [f"{pct(res[key][m])} {ci(BS.interval(boot[key][m]))}" for m in KEYS]
        w(f"| {key} | " + " | ".join(cells) + f" | {nt_solved(key)}/{n_nt} |")
    w("")
    w("'non-trivial solved' = test obligations not closed by the baseline tactics with at least one accepted sample from the "
      "model after the last stage, pooled over all E_j.")
    w("")
    w("Paired differences (points, 95% paired bootstrap interval):")
    w("")
    w("| Comparison | dLA | dACC | dF | dBWT |")
    w("|---|---|---|---|---|")
    comps = [(a, "D1 (S2)") for a in N_ARMS] + [(a, "B2") for a in N_ARMS] + [("D1 (S3)", "D1 (S2)")]
    for a, b in comps:
        cells = []
        for m in ("LA", "ACC", "F", "BWT"):
            dv, lh = diff(a, b, m)
            cells.append(f"{pct(dv)} {ci(lh)}")
        w(f"| {a} - {b} | " + " | ".join(cells) + " |")
    w("")
    rng = np.random.default_rng(cfg["bootstrap"]["seed"])
    base_nt = nt_vec("D1 (S2)")
    idx = rng.integers(0, len(base_nt), size=(cfg["bootstrap"]["resamples"], len(base_nt)))
    parts = []
    for a in N_ARMS:
        dv = nt_vec(a) - base_nt
        bs = dv[idx].sum(1)
        parts.append(f"{a} {int(dv.sum()):+d} [{np.percentile(bs, 2.5):.0f}, {np.percentile(bs, 97.5):.0f}]")
    w(f"Non-trivial solved minus D1 (S2), paired bootstrap over the {n_nt} non-trivial test obligations (count, 95% interval): " +
      "; ".join(parts) + ".")
    w("")
    w("## Checks (acceptance of the order)")
    w("")
    from ..data.stream import build_stream
    stream = build_stream(seed=cfg["stream"]["seed"], n_projects=cfg["stream"]["projects"])
    if stream.data_version() != m0["data_version"]:
        raise RuntimeError("rebuilt stream has another data version")
    be = stream.backend()
    full = stream.by_id()
    stage_of = {sid: t for t, sid in enumerate(stages, 1)}
    bem = [r for r in runs["N-B"]["channels"] if r["what"] == "statement" and r["emitted"]]
    b_ok = sum(1 for r in bem if r.get("proof") and r["accepted"] and
               be.check_statement(stages[r["stage"] - 1], "", r["statement"], r["proof"], 120).accepted)
    cem = [r for r in runs["N-C"]["channels"] if r["what"] == "statement" and r["emitted"]]
    c_cex = sum(1 for r in cem if r.get("counterexample") is not None)
    refuted = {(r["stage"], r["statement"]) for r in runs["N-C"]["channels"] if r["what"] == "refuted"}
    c_ref = sum(1 for r in cem if (r["stage"], r["statement"]) in refuted)
    seeds_c = [c for c in runs["N-C"]["conjectures"] if c.get("origin") == "channel"]
    c_seed_bad = sum(1 for c in seeds_c if (c["stage"], c["text"]) in refuted)
    t10 = b_ok == len(bem) and c_cex == 0 and c_ref == 0 and c_seed_bad == 0
    w(f"- **T10**: channel B emitted {len(bem)} statements; {b_ok} of them carry a machine proof that the checker accepts when "
      f"re-checked now from the log (backend.check_statement on the stage's snapshot). Channel C emitted {len(cem)} seeds; seeds "
      f"with a recorded counterexample: {c_cex}; emitted seeds equal to a refuted candidate: {c_ref}; conjecture-sleep seeds from C "
      f"equal to a refuted candidate: {c_seed_bad}. **{'passed' if t10 else 'FAILED'}**.")
    t4ref = str(cfg.get("t4_reference"))
    t4 = t4_check({a: runs[a] for a in runs}, test_sets)
    s1_evalsets = runs["B0"]["evalsets"]
    rec_eq = all(runs[x]["evalsets"] == s1_evalsets for x in s3)
    digests_ok = all(d == t4ref for d in t4["logged_digest"].values())
    w(f"- **T4**: recorded per-cell eval-set hashes of every S3 run equal S1's: {rec_eq}; target-id digest read back from every "
      f"verdict log equals {BT}{t4ref}{BT}: {digests_ok} ({len(set(t4['logged_digest'].values()))} distinct digest(s) over "
      f"{len(t4['logged_digest'])} runs); every line in its declared E_j: {t4['lines_in_declared_sets']}. "
      f"**{'passed' if rec_eq and digests_ok and t4['passed'] else 'FAILED'}**.")
    t8 = []
    for x in s3:
        want = runs[x]["meta"]["base"]["hash"]
        hs = [tr["base_hash"] for tr in runs[x]["train"]]
        t8.append((x, len(hs), all(h == want for h in hs), want))
    t8ok = all(ok and n == T for _, n, ok, _ in t8)
    w(f"- **T8** (base hash unchanged at every stage boundary): " + "; ".join(f"{a}: {n} boundaries equal to {BT}{h}{BT}: {ok}" for a, n, ok, h in t8)
      + f". **{'passed' if t8ok else 'FAILED'}**.")
    t9rows, t9ok = [], True
    for x in s3:
        r = runs[x]
        byid = {ln["verdict_id"]: ln for ln in r["dreams"]}
        dream_x = [e for e in r["train_examples"] if e["kind"] == "dream"]
        missing = sum(1 for e in dream_x if e["verdict_id"] not in byid)
        not_acc = sum(1 for e in dream_x if e["verdict_id"] in byid and not byid[e["verdict_id"]]["accepted"])
        guard_bad = sum(1 for e in dream_x if e["verdict_id"] in byid and byid[e["verdict_id"]]["guard"] != "pass")
        neg = [e["neg_verdict_id"] for e in dream_x if e.get("neg_verdict_id")]
        neg_bad = sum(1 for v_ in neg if v_ not in byid or byid[v_]["accepted"] or byid[v_]["guard"] != "pass")
        mat = [e for e in r["train_examples"] if e["source"] in ("human", "channel")]
        earlier = sum(1 for e in mat for i in e["source_ids"] if i in full and stage_of[full[i]["snapshot_id"]] != e["stage"])
        ch_x = [e for e in r["train_examples"] if e["source"] == "channel"]
        ok = missing == 0 and not_acc == 0 and guard_bad == 0 and neg_bad == 0 and earlier == 0
        t9ok &= ok
        t9rows.append(f"{x}: {len(dream_x)} dream examples, {missing} without a verdict line, {not_acc} rejected, {guard_bad} not "
                      f"guard-passed, {len(neg)} negatives ({neg_bad} bad); channel wake examples {len(ch_x)}; human or channel "
                      f"examples derived from an earlier window {earlier}")
    w(f"- **T9**: " + "; ".join(t9rows) + f". **{'passed' if t9ok else 'FAILED'}**.")
    gl, gok = [], True
    for x in s3:
        g = runs[x]["meta"]["guard"]
        can_ok = all(c["rule"] != "pass" for c in g["canaries"])
        cc = g.get("channel_canaries", [])
        cc_ok = all(c["items"] > 0 and c["refused"] == c["items"] for c in cc)
        gok &= g["training_raised"] == 0 and can_ok and cc_ok
        gl.append(f"{x}: training examples checked {g['training_checked']}, raised {g['training_raised']}; canaries raised "
                  f"{sum(c['rule'] != 'pass' for c in g['canaries'])}/{len(g['canaries'])}" +
                  (("; channel canaries refused " + ", ".join(f"{c['channel']} {c['refused']}/{c['items']}" for c in cc)) if cc else ""))
    w(f"- **Hold-out guard** (R4): " + "; ".join(gl) + f". **{'0 raises in training and every canary raised' if gok else 'FAILED'}**. "
      "Every channel item was guard-checked at emission (refusals in the yield tables); every training example was checked again "
      "inside the learner. The channel canaries run each channel's own extraction on test obligations (A, D, E mine a test proof; "
      "B and C emit a test statement, B with its proof; E instantiates a method into a test proof) and require every resulting "
      "item to be refused.")
    sig = lambda ln: (ln["stage"], ln["phase"], ln["target_id"], ln["sample"], ln["candidate_sha"], ln["accepted"])
    a2 = [sig(ln) for ln in runs["D1 (S2)"]["lines"]]
    a3 = [sig(ln) for ln in runs["D1 (S3)"]["lines"]]
    d2 = [sig(ln) for ln in runs["D1 (S2)"]["dreams"]]
    d3 = [sig(ln) for ln in runs["D1 (S3)"]["dreams"]]
    eq = a2 == a3 and d2 == d3
    w(f"- **Driver equivalence**: D1 re-run through the S3 driver with no channel vs S2's D1: eval verdict lines identical "
      f"(stage, phase, target, sample, candidate hash, verdict): {a2 == a3} ({len(a3)} lines); dream verdict lines identical: "
      f"{d2 == d3} ({len(d3)} lines). **{'passed' if eq else 'FAILED'}**.")
