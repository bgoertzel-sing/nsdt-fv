#!/usr/bin/env bash
# S3 from a clean checkout (plan 8.1): tests, then D1 (re-run, no channel) and N-A..N-E on pinned core pairs,
# then reports/S3.md regenerated twice from the logs (must be byte-identical, R3).
#   pip install -r requirements.txt   # pyyaml, pytest, numpy, torch (CPU)
#   S1's seed-0 base weights are needed (not committed): copy runs/S1/base/base.pt (or runs/S2/base/base.pt)
#   to runs/S3/base/base.pt; its hash is checked against configs/S3.yaml.
#   S2's D1 logs (runs/S2/D1, committed) are read by the report.
#   ./run_s3.sh
set -euo pipefail
cd "$(dirname "$0")"
python3 -m pytest -q
run() { taskset -c "$1" python3 -m nsdt_fv.eval.s3 --config nsdt_fv/configs/S3.yaml --arm "$2"; }
run 0,1 D1 & run 2,3 N-A & run 4,5 N-B & run 6,7 N-C & wait
run 0,1 N-D & run 2,3 N-E & wait
python3 -m nsdt_fv.eval.report_s3
cp nsdt_fv/reports/S3.md /tmp/S3.first.md
python3 -m nsdt_fv.eval.report_s3
cmp /tmp/S3.first.md nsdt_fv/reports/S3.md && echo "report regenerated byte-identically"
